@st.cache_resource
def load_artifacts():
    base_path = "models/trained_models"
    try:
        xgb_model = joblib.load(os.path.join(base_path, "xgboost_final.pkl"))
        lin_model = joblib.load(os.path.join(base_path, "linear_regression.pkl"))
        scaler = joblib.load(os.path.join(base_path, "scaler.pkl"))
        return xgb_model, lin_model, scaler
    except FileNotFoundError:
        st.error("CRITICAL ERROR: Model files not found. Please run 'main.py' first.")
        return None, None, None


xgb_model, lin_model, scaler = load_artifacts()

