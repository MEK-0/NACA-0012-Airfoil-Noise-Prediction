def user_input_features():
    frequency = st.sidebar.slider("Frequency (Hz)", 200, 20000, 2000, step=100)
    angle = st.sidebar.slider("Angle of Attack (°)", 0.0, 22.2, 4.0, step=0.1)
    chord = st.sidebar.slider("Chord Length (m)", 0.02, 0.30, 0.22, step=0.01)
    velocity = st.sidebar.slider("Free Stream Velocity (m/s)", 30.0, 71.3, 39.6, step=0.1)
    displacement = st.sidebar.slider("Suction Side Displacement (m)", 0.0004, 0.058, 0.0050, step=0.0001, format="%.4f")

    data = {
        'Frequency': frequency,
        'Angle_of_Attack': angle,
        'Chord_Length': chord,
        'Free_Stream_Velocity': velocity,
        'Suction_Side_Displacement_Thickness': displacement
    }
    return pd.DataFrame(data, index=[0])


input_df = user_input_features()

